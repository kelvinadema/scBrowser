"""Real-data browser workflows. Run against a local Shiny server; screenshots stay local."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright
OUT=Path(__file__).parent
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    errors=[]; checks=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.set_default_timeout(45000)
    def waitplot(id):
        page.wait_for_function('(id)=>document.getElementById(id).data?.length > 0',arg=id,timeout=90000)
        page.wait_for_timeout(800)
    def check(name):
        assert not page.locator('.shiny-output-error').count(), page.locator('.shiny-output-error').all_text_contents()
        checks.append(name); print('PASS',name,flush=True)
    def shot(name):
        page.screenshot(path=str(OUT/(name+'.png')))
    def tab(name):
        page.get_by_role('tab',name=name,exact=True).click();page.wait_for_timeout(800)
    page.goto(os.environ.get('BROWSER_URL','http://127.0.0.1:54032'),wait_until='networkidle')
    waitplot('umap3d');check('initial Cells annotation');shot('cells-desktop')
    page.locator('#gene_query').fill('MtNIN')
    page.wait_for_function("document.querySelector('#selection_summary').textContent.includes('MtNIN')")
    page.get_by_role('button',name='Selection details',exact=True).click()
    waitplot('fate_gene');waitplot('dissoc_gene');check('gene search updates details and evidence')
    # Both overlays must leave the camera, filter and selection intact.
    state=page.evaluate("JSON.stringify({cam:document.getElementById('umap3d').layout.scene.camera,gene:Shiny.shinyapp.$inputValues.gene})")
    for key in ['fate','dissoc']:
        page.locator(f'[data-evidence={key}]').click();page.wait_for_timeout(500);shot(key+'-evidence')
        page.keyboard.press('Escape')
    assert state==page.evaluate("JSON.stringify({cam:document.getElementById('umap3d').layout.scene.camera,gene:Shiny.shinyapp.$inputValues.gene})")
    check('evidence overlays preserve selection and camera')
    page.locator('[data-panel=samples]').click()
    page.locator('#samples_tip').click()
    page.wait_for_function("!document.querySelector('#sample_note').textContent.includes('29 of 29')")
    page.wait_for_timeout(500);shot('samples-laptop')
    page.locator('#sample-search').fill('p1')
    assert page.locator('.sample-group:visible').count()<8
    page.locator('#sample-search').fill('')
    first=page.locator('#samples_0 input[type=checkbox]').first
    first.uncheck();page.wait_for_timeout(700)
    assert page.locator('[data-group=samples_0]').evaluate('(el)=>el.indeterminate')
    page.locator('[data-group=samples_0]').check();page.wait_for_timeout(500)
    assert all(page.locator('#samples_0 input[type=checkbox]').evaluate_all('(els)=>els.map(e=>e.checked)'))
    page.locator('[data-group=samples_0]').uncheck();page.wait_for_timeout(500)
    assert not any(page.locator('#samples_0 input[type=checkbox]').evaluate_all('(els)=>els.map(e=>e.checked)'))
    page.locator('#samples_reset').click();page.wait_for_function("document.querySelector('#sample_note').textContent.includes('29 of 29')")
    check('sample presets, search, partial group state and reset')
    page.locator('[data-panel=sets]').click()
    page.locator('#geneset_text').fill('MtNIN MtNF-YA1 MtNIN missing_gene')
    page.wait_for_function("document.querySelector('#geneset_note').textContent.includes('1 duplicate')")
    page.locator('#use_set').click();page.wait_for_function("document.querySelector('#selection_summary').textContent.includes('Active set:')")
    page.locator('#custom_name').fill('UI validation set');page.locator('#custom_save').click()
    page.wait_for_function("JSON.parse(localStorage.getItem('mt_browser_custom_sets_v1')||'{}')['UI validation set']?.length===2")
    check('parse, deduplicate, unmatched report, use and save set');shot('gene-sets')
    page.locator('#geneset_text').fill('MtNIN MtNF-YA1 MtrunA17_Chr3g0134941')
    page.locator('#custom_name').fill('UI validation set');page.locator('#custom_save').click()
    page.wait_for_function("JSON.parse(localStorage.getItem('mt_browser_custom_sets_v1'))['UI validation set'].length===3")
    page.reload(wait_until='networkidle');waitplot('umap3d')
    page.locator('[data-panel=sets]').click()
    page.locator('#geneset_preset').select_option('custom:UI validation set')
    page.wait_for_function("document.querySelector('#geneset_note').textContent.includes('3 Genes matched')")
    page.locator('#geneset_text').fill('MtNIN MtNF-YA1');page.locator('#use_set').click()
    check('edit named set and restore browser persistence after reload')
    tab('Expression');waitplot('dotplot')
    assert 'Gene-set score dot plot' in page.locator('#expression_heading').inner_text()
    page.locator('input[name=expr_view][value=heat]').check();waitplot('dotplot')
    page.wait_for_function("document.getElementById('dotplot').layout.meta?.genes?.length===2")
    selected=page.evaluate("document.getElementById('dotplot').layout.meta.genes[1]")
    page.evaluate("id=>document.getElementById('dotplot').emit('plotly_click',{points:[{y:1}]})",selected)
    page.wait_for_function('(id)=>Shiny.shinyapp.$inputValues.gene===id',arg=selected)
    assert page.evaluate("Shiny.shinyapp.$inputValues.sel_kind")=='set'
    assert page.evaluate("document.getElementById('dotplot').layout.meta.genes.length")==2
    check('dot/heat toggle and row inspection retain active set')
    page.locator('[data-panel=sets]').click();page.locator('#geneset_preset').select_option('GEP12')
    page.wait_for_function("document.querySelector('#geneset_note').textContent.includes('200 Genes matched')")
    page.locator('#use_set').click();page.wait_for_function("document.getElementById('dotplot').layout.meta?.genes?.length===200",timeout=90000)
    page.get_by_role('button',name='Plot settings',exact=True).click()
    page.wait_for_selector('#heat_cluster')
    page.locator('#heat_clustering').uncheck();page.wait_for_timeout(1200)
    assert 'Clustering disabled' in page.locator('#heat_note').inner_text()
    page.locator('#heat_clustering').check();page.locator('#heat_k').fill('4');page.locator('#heat_k').press('Tab')
    page.wait_for_function("document.querySelector('#heat_note').textContent.includes('4 clusters')",timeout=90000)
    page.locator('input[name=heat_scale][value=raw]').check();page.wait_for_timeout(800);shot('heatmap-desktop')
    page.locator('#heat_cluster').select_option('C2');page.locator('#heat_use_cluster').click()
    page.wait_for_function("document.querySelector('#selection_summary').textContent.includes('C2')")
    check('heatmap scales, clustering toggle, cluster count and saved cluster set')
    tab('Genes');waitplot('geneumap')
    page.locator('input[name=gene_map_dim][value="3"]').check();page.wait_for_function("document.getElementById('geneumap').data[0].type==='scatter3d'")
    page.locator('input[name=gene_map_dim][value="2"]').check();page.wait_for_timeout(1000);shot('genes-desktop')
    point=page.evaluate("document.getElementById('geneumap').data.find(t=>t.customdata?.length).customdata[0]")
    page.evaluate("point=>document.getElementById('geneumap').emit('plotly_click',{points:[{customdata:point}]})",point)
    page.wait_for_function('(id)=>Shiny.shinyapp.$inputValues.gene===id',arg=point[0])
    assert page.evaluate("Shiny.shinyapp.$inputValues.sel_kind")== 'set'
    check('gene map 2D, 3D and click inspection')
    tab('Fate association');waitplot('fateplot');page.locator('input[name=fate_measure][value=detection]').check()
    page.locator('input[name=fate_platform][value=BD]').check();page.wait_for_timeout(1500);shot('fate-desktop')
    assert page.locator('#panel-settings').is_hidden(), 'Irrelevant settings should close on Fate'
    page.locator('input[name=fate_target][value=inspected]').check();page.wait_for_timeout(1200)
    assert page.evaluate("document.getElementById('fateplot').layout.yaxis.title.text")=='Expressing cells (weighted fraction)'
    page.locator('input[name=fate_target][value=active]').check();page.wait_for_timeout(800)
    assert page.evaluate("Shiny.shinyapp.$inputValues.sel_kind")== 'set'
    check('fate measure, platform and inspected-gene controls preserve active set')
    tab('Cells');page.get_by_role('button',name='Plot settings',exact=True).click()
    page.locator('#max_points').select_option('50000');page.wait_for_function("document.getElementById('umap3d')._fullData.reduce((n,t)=>n+(t.x?.length||0),0)===50000")
    page.locator('#facet').select_option('ch5_region');page.wait_for_timeout(1500)
    page.locator('#facet_context').uncheck();page.wait_for_timeout(500)
    page.locator('#facet').select_option('');page.locator('#reset_view').click();page.wait_for_timeout(800)
    page.locator('#opacity').evaluate("el=>$(el).data('ionRangeSlider').update({from:0.5})")
    page.locator('#opacity').dispatch_event('change');page.wait_for_timeout(500)
    page.get_by_role('button',name='Fullscreen',exact=True).click()
    page.wait_for_function('!!document.fullscreenElement');page.evaluate('document.exitFullscreen()')
    check('drawing budget, faceting, opacity, reset and fullscreen')
    page.set_viewport_size({'width':1366,'height':768});page.wait_for_timeout(1000);shot('cells-laptop')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.locator('#panel-settings [data-panel=none]').click();page.wait_for_timeout(500);shot('cells-laptop-wide')
    page.set_viewport_size({'width':1920,'height':1080});page.wait_for_timeout(500);shot('cells-large-desktop')
    check('laptop/desktop sizes and closing panel resize')
    controls=page.evaluate("[...document.querySelectorAll('input[type=checkbox]:checked,input[type=radio]:checked')].map(e=>getComputedStyle(e).backgroundColor)")
    assert all(c=='rgb(37, 37, 37)' for c in controls), controls
    assert not errors, errors
    (OUT/'browser-results.json').write_text(json.dumps({'checks':checks,'browser_errors':errors},indent=2))
    print('PASS ALL',len(checks),flush=True)
    browser.close()
